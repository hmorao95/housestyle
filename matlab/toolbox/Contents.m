% housestyle  Paper figures in the mshipping house style
% Version 1.0.0 (R2026a) 31-Oct-2026
%
% Figure and panels
%   hs_figure  - New figure, 1180 px wide, 30 + 285 px per row of panels
%   hs_axes    - Start a panel: subplot, hold, grid and box on
%   hs_finish  - Bold title, LaTeX labels, 10 pt ticks, thin crowded y ticks
%
% Marks
%   hs_irf     - One response panel: black median, blue band, zero line
%   hs_line    - A series in house order: black, orange dashed, green dash-dot, purple dots
%   hs_band    - Credible or confidence band as a translucent blue patch
%   hs_zero    - Dashed zero line, only when 0 lies inside the y-limits
%   hs_shade   - Grey shaded episode behind the data
%   hs_event   - Black dot with a short 8 pt label
%
% Colors and output
%   hs_colors  - House palette
%   hs_outdir  - Get or set the folder hs_export writes to
%   hs_export  - White background, 300 dpi PNG through export_fig
%
